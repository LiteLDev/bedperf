// Regenerates the root pnpm-workspace.yaml from vendor/bedboo/pnpm-workspace.yaml.
// bedboo only works inside a pnpm workspace that carries its overrides and patches,
// so we copy its settings verbatim, re-root the patch paths, and add our own packages.
// Run after bumping the bedboo submodule:  node scripts/sync-bedboo.mjs && pnpm install
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'vendor/bedboo/pnpm-workspace.yaml'), 'utf8').replace(/\r\n/g, '\n')

const lines = src.split('\n')
const out = []
let skippingPackages = false
for (const line of lines) {
  if (line.startsWith('packages:')) { skippingPackages = true; continue }
  if (skippingPackages) {
    if (line.startsWith('  - ') || line.trim() === '') continue
    skippingPackages = false
  }
  out.push(line.replace(/: patches\//, ': vendor/bedboo/patches/'))
}

const header = `# GENERATED by scripts/sync-bedboo.mjs from vendor/bedboo/pnpm-workspace.yaml — do not edit by hand.
packages:
  - packages/*
  - vendor/bedboo/packages/bedboo
  - vendor/bedboo/packages/bedrock-data
`
writeFileSync(join(root, 'pnpm-workspace.yaml'), header + '\n' + out.join('\n').replace(/^\n+/, ''))
console.log('pnpm-workspace.yaml regenerated')
